from __future__ import annotations

from pathlib import Path

import pyarrow as pa
import pytest

from textual_fastdatatable.backend import ArrowBackend
from textual_fastdatatable.extension_types import (
    EXTENSION_METADATA_KEY,
    EXTENSION_NAME_KEY,
    ParquetVariantType,
    canonicalize,
)
from textual_fastdatatable.variant import (
    MAX_NESTING_DEPTH,
    VariantError,
    variant_to_python,
)

CORPUS_PATH = Path(__file__).parents[1] / "data" / "parquet_variant_corpus.tsv"

NO_KEYS = bytes([0x01, 0x00, 0x00])
"""Metadata of version 1, with one-byte offsets and an empty dictionary."""

PARQUET_VARIANT = {
    EXTENSION_NAME_KEY: b"arrow.parquet.variant",
    EXTENSION_METADATA_KEY: b"",
}
VARIANT_STORAGE = pa.struct(
    [
        pa.field("metadata", pa.binary(), nullable=False),
        pa.field("value", pa.binary()),
    ]
)


def duckdb_corpus() -> list[tuple[str, str, str]]:
    """(hex metadata, hex value, repr) triples, generated by duckdb 2.0.0.

    Every primitive type duckdb writes, the ends of the temporal ranges, objects
    and arrays that need wider offsets, ids and counts, and nesting. Each repr is
    of the value duckdb's own client converts the same VARIANT to.
    """
    lines = CORPUS_PATH.read_text(encoding="utf-8").splitlines()
    rows = [line.split("\t") for line in lines if not line.startswith("#")]
    return [(metadata, value, expected) for metadata, value, expected in rows]


def short_string(text: str) -> bytes:
    data = text.encode()
    return bytes([len(data) << 2 | 1]) + data


def array_of(*values: bytes) -> bytes:
    """An array with a one-byte count and four-byte offsets."""
    offsets = [0]
    for value in values:
        offsets.append(offsets[-1] + len(value))
    header = bytes([0x03 << 2 | 0x03, len(values)])
    encoded_offsets = b"".join(offset.to_bytes(4, "little") for offset in offsets)
    return header + encoded_offsets + b"".join(values)


def variant_table(*rows: tuple[bytes, bytes] | None) -> pa.Table:
    storage = pa.array(
        [
            None if row is None else {"metadata": row[0], "value": row[1]}
            for row in rows
        ],
        type=VARIANT_STORAGE,
    )
    field = pa.field("v", VARIANT_STORAGE, metadata=PARQUET_VARIANT)
    return pa.Table.from_arrays([storage], schema=pa.schema([field]))


@pytest.mark.parametrize(("hex_metadata", "hex_value", "expected"), duckdb_corpus())
def test_values_match_duckdb(hex_metadata: str, hex_value: str, expected: str) -> None:
    value = variant_to_python(bytes.fromhex(hex_metadata), bytes.fromhex(hex_value))
    assert repr(value) == expected


@pytest.mark.parametrize(
    ("metadata", "value"),
    [
        pytest.param(b"", short_string("a"), id="no metadata"),
        pytest.param(bytes([0x02, 0x00, 0x00]), short_string("a"), id="bad version"),
        pytest.param(bytes([0x01, 0x01, 0x00, 0x09]), b"\x00", id="keys cut short"),
        pytest.param(NO_KEYS, b"", id="no value"),
        pytest.param(NO_KEYS, bytes([0x05]), id="short string cut short"),
        pytest.param(NO_KEYS, bytes([0x54]), id="unknown primitive"),
        pytest.param(NO_KEYS, bytes([0x14, 0x01]), id="int32 cut short"),
        pytest.param(NO_KEYS, bytes([0x09, 0xFF, 0xFE]), id="string not utf-8"),
        pytest.param(
            NO_KEYS, bytes([0x44]) + (10**12).to_bytes(8, "little"), id="time"
        ),
        pytest.param(NO_KEYS, bytes([0x02, 0x01, 0x00, 0x00, 0x01, 0x00]), id="no key"),
        pytest.param(NO_KEYS, bytes([0x03, 0x02, 0x00, 0x01]), id="array cut short"),
    ],
)
def test_bytes_that_are_not_a_variant_raise(metadata: bytes, value: bytes) -> None:
    with pytest.raises(VariantError):
        variant_to_python(metadata, value)


def test_nesting_past_the_limit_raises_rather_than_recursing() -> None:
    value = bytes([0x00])  # null
    for _ in range(MAX_NESTING_DEPTH):
        value = array_of(value)
    with pytest.raises(VariantError, match="nests deeper"):
        variant_to_python(NO_KEYS, value)


def test_offsets_that_share_one_value_cannot_multiply_it() -> None:
    """Shared offsets would otherwise decode 2**depth values from a few bytes."""
    value = bytes([0x00])
    for _ in range(40):
        # two elements, both at offset 0
        value = bytes([0x03, 0x02, 0x00, 0x00, len(value)]) + value
    with pytest.raises(VariantError, match="more than it has bytes"):
        variant_to_python(NO_KEYS, value)


def test_offsets_that_share_one_string_cannot_multiply_it() -> None:
    """Each element is one value, but would be a copy of the whole string."""
    text = b"x" * 1000
    string = bytes([0x40]) + len(text).to_bytes(4, "little") + text
    count = 200
    # a four-byte count and one-byte offsets, all of them 0
    header = bytes([0x03 | 0x04 << 2]) + count.to_bytes(4, "little")
    value = header + bytes(count + 1) + string
    with pytest.raises(VariantError, match="more than it has bytes"):
        variant_to_python(NO_KEYS, value)


def test_an_object_that_repeats_a_key_raises() -> None:
    metadata = bytes([0x01, 0x01, 0x00, 0x01]) + b"a"
    one = bytes([0x0C, 0x01])
    # two fields, both key 0, at offsets 0 and 2
    value = bytes([0x02, 0x02, 0x00, 0x00, 0x00, 0x02, 0x04]) + one + one
    with pytest.raises(VariantError, match="repeats a key"):
        variant_to_python(metadata, value)


def test_a_tagged_struct_becomes_a_variant() -> None:
    canonicalized = canonicalize(variant_table((NO_KEYS, short_string("hi"))))

    assert isinstance(canonicalized.schema.field(0).type, ParquetVariantType)
    assert canonicalized.column(0).to_pylist() == ["hi"]


@pytest.mark.parametrize(
    "storage",
    [
        pytest.param(pa.binary(), id="not a struct"),
        pytest.param(
            pa.struct([("metadata", pa.binary()), ("value", pa.string())]),
            id="value not binary",
        ),
        pytest.param(
            pa.struct(
                [
                    ("metadata", pa.binary()),
                    ("value", pa.binary()),
                    ("typed_value", pa.int64()),
                ]
            ),
            id="shredded",
        ),
    ],
)
def test_a_storage_type_a_variant_is_not_stored_as_is_declined(
    storage: pa.DataType,
) -> None:
    field = pa.field("v", storage, metadata=PARQUET_VARIANT)
    data = pa.Table.from_arrays([pa.nulls(1, storage)], schema=pa.schema([field]))

    assert canonicalize(data) is data


def test_the_backend_shows_what_a_variant_holds_and_keeps_the_callers_bytes() -> None:
    hi = (NO_KEYS, short_string("hi"))
    listed = (NO_KEYS, array_of(short_string("a"), bytes([0x04])))
    backend = ArrowBackend(variant_table(hi, listed, None))

    assert backend.get_column_at(0) == ["hi", ["a", True], None]
    assert backend.source_data.column(0).to_pylist()[0] == {
        "metadata": NO_KEYS,
        "value": short_string("hi"),
    }


def test_a_variant_column_is_measured_from_every_value_not_the_first() -> None:
    """A uuid's width is fixed, but the next value in a variant need not be one."""
    a_uuid = bytes([0x50]) + bytes(16)
    long_text = "x" * 50
    backend = ArrowBackend(
        variant_table((NO_KEYS, a_uuid), (NO_KEYS, short_string(long_text)))
    )

    assert backend.column_content_widths == [len(long_text)]


def test_bytes_tagged_as_a_variant_that_are_not_one_stay_its_buffers() -> None:
    backend = ArrowBackend(variant_table((NO_KEYS, bytes([0x54])), None))
    buffers = {"metadata": NO_KEYS, "value": bytes([0x54])}

    assert backend.get_cell_at(0, 0) == buffers
    assert backend.get_column_at(0) == [buffers, None]


VARIANT_FIELD = pa.field("v", VARIANT_STORAGE, metadata=PARQUET_VARIANT)
B = {"metadata": NO_KEYS, "value": short_string("b")}
A = {"metadata": NO_KEYS, "value": short_string("a")}


@pytest.mark.parametrize(
    ("storage_type", "rows", "expected"),
    [
        pytest.param(pa.list_(VARIANT_FIELD), [[B], [A]], [["a"], ["b"]], id="list"),
        pytest.param(
            pa.struct([VARIANT_FIELD]),
            [{"v": B}, {"v": A}],
            [{"v": "a"}, {"v": "b"}],
            id="struct",
        ),
    ],
)
def test_a_table_holding_a_nested_variant_sorts(
    storage_type: pa.DataType, rows: list[object], expected: list[object]
) -> None:
    backend = ArrowBackend(
        pa.table({"id": [2, 1], "nested": pa.array(rows, type=storage_type)})
    )

    backend.sort("id")

    assert backend.get_column_at(0) == [1, 2]
    assert backend.get_column_at(1) == expected
