def test_an_opaque_type_that_is_not_duckdbs_bignum_is_left_alone(
    extension_type: pa.OpaqueType,
) -> None:
    storage = pa.nulls(1, extension_type.storage_type)
    data = pa.table({"o": pa.ExtensionArray.from_storage(extension_type, storage)})

    assert canonicalize(data) is data


@pytest.mark.parametrize(
    "storage", [pa.binary(), pa.large_binary(), pa.binary_view()], ids=str
)
def test_every_binary_storage_is_read(storage: pa.DataType) -> None:
    extension_type = pa.opaque(storage, type_name="bignum", vendor_name="DuckDB")
    data = pa.table({"n": bignum_array(256, extension_type=extension_type)})

    assert canonicalize(data).column(0).to_pylist() == [256]


def test_the_backend_shows_integers_and_keeps_the_callers_bytes() -> None:
    big = 123456789012345678901234567890
    backend = ArrowBackend(bignum_table(big, -1, 0, None))

    assert backend.get_cell_at(0, 0) == big
    assert backend.get_row_at(1) == [-1]
    assert backend.get_column_at(0) == [big, -1, 0, None]
    # the caller handed over duckdb's encoding, and source_data is the caller's table
    assert backend.source_data.schema.field(0).type == DUCKDB_BIGNUM
    assert backend.source_data.column(0).to_pylist() == [
        encode(big),
        encode(-1),
        encode(0),
        None,
    ]


def test_a_bignum_column_is_as_wide_as_its_widest_integer() -> None:
    big = -(7**500)
    backend = ArrowBackend(bignum_table(1, big, None))

    assert backend.column_content_widths == [measure_width(big)]


def test_a_bignum_past_pythons_text_limit_measures_and_renders() -> None:
    value = 10**5000 - 1
    backend = ArrowBackend(bignum_table(value))

    assert backend.column_content_widths == [measure_width(Decimal(value))]
    assert display_text(backend.get_cell_at(0, 0)) == f"{Decimal(value):n}"


def test_bytes_tagged_as_a_bignum_that_are_not_one_stay_bytes() -> None:
    backend = ArrowBackend(bignum_table(b"\x80\x00\x05\x01", 7))

    assert backend.get_cell_at(0, 0) == b"\x80\x00\x05\x01"
    assert backend.get_column_at(0) == [b"\x80\x00\x05\x01", 7]


def test_a_bignum_column_sorts_in_numeric_order() -> None:
    """duckdb's encoding sorts as its values do, so the storage's order is theirs."""
    values = [256, -1, 0, -256, 1, 10**30, -(10**30), 255, -255, 2**64]
    backend = ArrowBackend(bignum_table(*values))

    backend.sort("n")
    ascending = backend.get_column_at(0)
    backend.sort([("n", "descending")])

    assert ascending == sorted(values)
    assert backend.get_column_at(0) == sorted(values, reverse=True)


def test_a_bignum_cell_cannot_be_updated() -> None:
    backend = ArrowBackend(bignum_table(1, 2))

    with pytest.raises(TypeError, match="not the values it stores"):
        backend.update_cell(0, 0, 3)

    assert backend.get_column_at(0) == [1, 2]


BIGNUM_FIELD = pa.field("n", DUCKDB_BIGNUM)
STORAGE_FIELD = pa.field("n", pa.binary())


def nested_array(nest: Callable[[pa.Field], pa.DataType], value: object) -> pa.Array:
    """One `value`, of the type `nest` makes around a BIGNUM field."""
    storage = pa.array([value], type=nest(STORAGE_FIELD))
    assert isinstance(storage, pa.Array)
    return storage.cast(nest(BIGNUM_FIELD))


@pytest.mark.parametrize(
    ("nest", "value", "expected"),
    [
        pytest.param(pa.list_, [encode(-5), None], [-5, None], id="list"),
        pytest.param(pa.large_list, [encode(10**30)], [10**30], id="large list"),
        pytest.param(
            lambda field: pa.list_(field, 2),
            [encode(1), encode(2)],
            [1, 2],
            id="fixed list",
        ),
        pytest.param(
            lambda field: pa.struct([field]),
            {"n": encode(-256)},
            {"n": -256},
            id="struct",
        ),
        pytest.param(
            lambda field: pa.map_(
                field.with_name("key").with_nullable(False), field.with_name("value")
            ),
            [(encode(3), encode(4))],
            [(3, 4)],
            id="map",
        ),
        pytest.param(
            lambda field: pa.list_(pa.field("s", pa.struct([field]))),
            [{"n": encode(2**64)}],
            [{"n": 2**64}],
            id="list of struct",
        ),
    ],
)
def test_a_nested_bignum_is_converted_too(
    nest: Callable[[pa.Field], pa.DataType], value: object, expected: object
) -> None:
    """duckdb types the BIGNUM inside a LIST or a STRUCT, not the column."""
    data = pa.table({"nested": nested_array(nest, value)})

    assert canonicalize(data).column(0).to_pylist() == [expected]
    assert ArrowBackend(data).get_cell_at(0, 0) == expected


def test_a_table_holding_a_nested_bignum_sorts() -> None:
    nested = pa.chunked_array(
        [nested_array(pa.list_, [encode(2)]), nested_array(pa.list_, [encode(-1)])]
    )
    backend = ArrowBackend(pa.table({"id": [2, 1], "nested": nested}))

    backend.sort("id")

    assert backend.get_column_at(0) == [1, 2]
    assert backend.get_column_at(1) == [[-1], [2]]
